#!/usr/bin/env python3
"""Regenerate Tiny64's curated BearSSL trust anchors from bundled root PEMs.

Host-only build helper. Requires Python cryptography. Root certificates are
not downloaded at build/runtime; review provenance/fingerprints before updating.
"""
from pathlib import Path
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec

HERE = Path(__file__).resolve().parent.parent
ROOTS = [
    "ISRG_Root_X1",
    "DigiCert_Global_Root_G2",
    "DigiCert_Global_Root_CA",
    "DigiCert_Global_Root_G3",
    "GTS_Root_R1",
    "GTS_Root_R2",
    "GTS_Root_R3",
    "GTS_Root_R4",
    "GlobalSign_Root_CA_-_R3",
    "GlobalSign_Root_CA_-_R6",
    "Sectigo_Public_Server_Authentication_Root_R46",
    "Comodo_AAA_Services_root",
]
CURVES = {"secp256r1": "BR_EC_secp256r1", "secp384r1": "BR_EC_secp384r1", "secp521r1": "BR_EC_secp521r1"}


def bytes_c(name, data):
    lines = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+12]) + ",")
    lines.append("};")
    return "\n".join(lines)


out = ["/* Generated by tls/tools/generate_trust_anchors.py from the bundled PEMs.",
       " * Curated roots, NOT a complete OS CA bundle. No trust-on-first-use.",
       " * The static arrays are immutable; BearSSL's API uses non-const pointers.",
       " */", '#include "trust_anchors.h"', ""]
anchors = []
for i, name in enumerate(ROOTS):
    cert = x509.load_pem_x509_certificate((HERE / "roots" / (name + ".pem")).read_bytes())
    pub = cert.public_key()
    if cert.issuer != cert.subject:
        raise ValueError(f"not self-issued: {name}")
    print(name, cert.fingerprint(hashes.SHA256()).hex())
    out.append(f"/* {name}; SHA-256(DER) = {cert.fingerprint(hashes.SHA256()).hex()} */")
    out.append(bytes_c(f"ta_dn_{i}", cert.subject.public_bytes()))
    if isinstance(pub, rsa.RSAPublicKey):
        nums = pub.public_numbers()
        n = nums.n.to_bytes((nums.n.bit_length()+7)//8, "big")
        e = nums.e.to_bytes((nums.e.bit_length()+7)//8, "big")
        out.append(bytes_c(f"ta_n_{i}", n))
        out.append(bytes_c(f"ta_e_{i}", e))
        anchors.append(f"    {{ {{ (unsigned char *)ta_dn_{i}, sizeof ta_dn_{i} }}, BR_X509_TA_CA, "
                       f"{{ BR_KEYTYPE_RSA, {{ .rsa = {{ (unsigned char *)ta_n_{i}, sizeof ta_n_{i}, "
                       f"(unsigned char *)ta_e_{i}, sizeof ta_e_{i} }} }} }} }},")
    elif isinstance(pub, ec.EllipticCurvePublicKey):
        curve = CURVES[pub.curve.name]
        q = pub.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        out.append(bytes_c(f"ta_q_{i}", q))
        anchors.append(f"    {{ {{ (unsigned char *)ta_dn_{i}, sizeof ta_dn_{i} }}, BR_X509_TA_CA, "
                       f"{{ BR_KEYTYPE_EC, {{ .ec = {{ {curve}, (unsigned char *)ta_q_{i}, sizeof ta_q_{i} }} }} }} }},")
    else:
        raise ValueError(f"unsupported key type for {name}")
    out.append("")
out.append("const br_x509_trust_anchor tiny64_trust_anchors[] = {")
out.extend(anchors)
out.append("};")
out.append("const size_t tiny64_trust_anchor_count = sizeof tiny64_trust_anchors / sizeof tiny64_trust_anchors[0];")
(HERE / "trust_anchors.c").write_text("\n".join(out) + "\n")
